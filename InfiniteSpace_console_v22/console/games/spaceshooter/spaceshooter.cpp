    bool aabb(float x1, float y1, float x2, float y2, float s = 12.0f) {
        return std::abs(x1 - x2) < s && std::abs(y1 - y2) < s;
    }

    void check_collisions(Engine& e) {
        // Player bullets vs enemies
        for (auto& b : bullets) {
            if (!b.active || !b.from_player) continue;
            for (auto& en : enemies) {
                if (!en.active) continue;
                if (aabb(b.x, b.y, en.x, en.y, 18.0f)) {
                    b.active = false;
                    en.hp -= 1;
                    if (en.hp <= 0) {
                        en.active = false;
                        spawn_explosion(en.x, en.y);
                        progress.score += (en.type == 0) ? 100 : 160;
                        progress.credits += (en.type == 0) ? 3 : 5;
                        on_enemy_killed(en.x, en.y, en.type);
                        e.audio.tone(1, 320, 110, 50);
                    }
                    break;
                }
            }
        }

        // Enemy bullets vs player
        for (auto& b : bullets) {
            if (!b.active || b.from_player) continue;
            if (aabb(b.x, b.y, player.x, player.y, 20.0f)) {
                b.active = false;
                take_damage(18.0f, &e);
            }
        }

        // Enemies vs player
        for (auto& en : enemies) {
            if (!en.active) continue;
            if (aabb(en.x, en.y, player.x, player.y, 24.0f)) {
                en.active = false;
                spawn_explosion(en.x, en.y);
                take_damage(28.0f, &e);
            }
        }
    }

