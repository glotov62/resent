    void draw(Renderer& r) override {
        r.clear(COL_BG);

        // Stars always
        for (const auto& s : stars) {
            r.pixel((int)s.x, (int)s.y, s.color);
        }

        if (state == GameState::TITLE) {
            draw_title(r);
            return;
        }

        // Game objects
        draw_player(r);
        draw_bullets(r);
        draw_enemies(r);
        draw_boss(r);
        draw_pickups(r);
        draw_asteroids(r);
        draw_explosions(r);
        draw_hud(r);

        if (state == GameState::UPGRADE) {
            draw_upgrade_overlay(r);
        }
        if (state == GameState::PAUSED) {
            r.text(SCREEN_W/2 - 30, SCREEN_H/2 - 4, "PAUSED", COL_UI, 2);
        }
    }

