    void blit16(Renderer& r, const uint16_t* data, int w, int h, int dx, int dy, uint16_t key = 0) {
        for (int y = 0; y < h; ++y) {
            int sy = dy + y;
            if ((unsigned)sy >= (unsigned)SCREEN_H) continue;
            for (int x = 0; x < w; ++x) {
                uint16_t c = data[y * w + x];
                if (c == key) continue;
                int sx = dx + x;
                if ((unsigned)sx < (unsigned)SCREEN_W)
                    r.pixel(sx, sy, c);
            }
        }
    }


    void blit_sprite(Renderer& r, const uint16_t* data, int w, int h, int dx, int dy) {
        for (int y = 0; y < h; ++y) {
            int sy = dy + y;
            if ((unsigned)sy >= (unsigned)SCREEN_H) continue;
            const uint16_t* row = data + y * w;
            for (int x = 0; x < w; ++x) {
                uint16_t c = row[x];
                if (c == 0) continue;
                int sx = dx + x;
                if ((unsigned)sx < (unsigned)SCREEN_W)
                    r.pixel(sx, sy, c);
            }
        }
    }

