    void update_events(float dt) {
        if (boss.active) return;
        event_timer -= dt;

        if (event_type == 0 && event_timer <= 0) {
            // start asteroid field
            event_type = 1;
            event_life = 18.0f + randf() * 8.0f;
            event_timer = 40.0f + randf() * 25.0f;
            for (int i = 0; i < MAX_ASTEROIDS; ++i) {
                asteroids[i].active = true;
                asteroids[i].x = (float)rand_int(SCREEN_W);
                asteroids[i].y = -20.0f - randf() * 200.0f;
                asteroids[i].vx = (randf() - 0.5f) * 40.0f;
                asteroids[i].vy = 50.0f + randf() * 80.0f;
                asteroids[i].r = 4.0f + randf() * 8.0f;
            }
        }

        if (event_type == 1) {
            event_life -= dt;
            for (auto& a : asteroids) {
                if (!a.active) continue;
                a.x += a.vx * dt;
                a.y += a.vy * dt;
                if (a.y > SCREEN_H + 20) {
                    if (event_life > 0) {
                        a.y = -15;
                        a.x = (float)rand_int(SCREEN_W);
                    } else a.active = false;
                }
                // hit player
                if (fabsf(a.x - player.x) < a.r + 12 && fabsf(a.y - player.y) < a.r + 14) {
                    a.active = false;
                    take_damage(12.0f);
                    spawn_explosion(a.x, a.y);
                }
                // bullets destroy asteroids
                for (auto& b : bullets) {
                    if (!b.active || !b.from_player) continue;
                    if (fabsf(b.x - a.x) < a.r + 4 && fabsf(b.y - a.y) < a.r + 4) {
                        b.active = false;
                        a.active = false;
                        spawn_explosion(a.x, a.y);
                        progress.score += 15;
                        if (rand_int(100) < 25) spawn_pickup(a.x, a.y, PickupType::Credits);
                        break;
                    }
                }
            }
            if (event_life <= 0) {
                bool any = false;
                for (auto& a : asteroids) if (a.active) any = true;
                if (!any) event_type = 0;
            }
        }
    }

