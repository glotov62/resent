    void update_pickups(Engine& e, float dt) {
        // timers
        if (power_weapon > 0) power_weapon -= dt;
        if (power_rapid > 0) power_rapid -= dt;
        if (power_magnet > 0) power_magnet -= dt;

        for (auto& p : pickups) {
            if (!p.active) continue;
            p.y += p.vy * dt;
            p.life -= dt;
            if (p.life <= 0 || p.y > SCREEN_H + 10) { p.active = false; continue; }

            // magnet
            if (power_magnet > 0) {
                float dx = player.x - p.x;
                float dy = player.y - p.y;
                float d = sqrtf(dx*dx + dy*dy) + 0.1f;
                p.x += dx / d * 180.0f * dt;
                p.y += dy / d * 180.0f * dt;
            }

            // collect
            if (fabsf(p.x - player.x) < 18 && fabsf(p.y - player.y) < 20) {
                p.active = false;
                switch (p.type) {
                    case PickupType::Credits:
                        progress.credits += 5 + rand_int(8);
                        progress.score += 25;
                        e.audio.tone(2, 880, 60, 40);
                        break;
                    case PickupType::WeaponBoost:
                        power_weapon = 14.0f;
                        e.audio.tone(0, 600, 120, 80);
                        break;
                    case PickupType::ShieldRestore:
                        player.shield = std::min(player.shield_max, player.shield + 40.0f);
                        e.audio.tone(1, 500, 100, 60);
                        break;
                    case PickupType::RapidFire:
                        power_rapid = 12.0f;
                        e.audio.tone(0, 700, 100, 70);
                        break;
                    case PickupType::Magnet:
                        power_magnet = 11.0f;
                        e.audio.tone(2, 400, 90, 50);
                        break;
                }
            }
        }
    }

