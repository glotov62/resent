    // ----------------------------------------------------------
    void update(Engine& e, float dt) override {
        if (state == GameState::TITLE) {
            update_title(e, dt);
            return;
        }

        if (state == GameState::UPGRADE) {
            update_upgrade(e, dt);
            return;
        }

        if (state == GameState::PAUSED) {
            if (e.input.hit(BTN_START) || e.input.hit(BTN_B)) {
                state = GameState::PLAYING;
            }
            return;
        }

        // === PLAYING ===
        game_time += dt;
        update_player(e, dt);
        update_stars(dt);
        update_bullets(dt);
        update_enemies(dt);
        update_explosions(dt);
        spawn_enemies(dt);
        update_waves(dt);
        update_boss(e, dt);
        update_pickups(e, dt);
        update_events(dt);
        check_collisions(e);

        // Open upgrade menu
        if (e.input.hit(BTN_START)) {
            state = GameState::UPGRADE;
        }
    }

