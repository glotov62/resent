    void spawn_explosion(float x, float y) {
        // Main explosion object (ring + flash)
        for (auto& ex : explosions) {
            if (!ex.active) {
                ex.x = x; ex.y = y;
                ex.radius = 2.0f;
                ex.max_radius = 28.0f + randf() * 12.0f;
                ex.life = 0.55f;
                ex.flash = 0.18f;
                ex.active = true;
                break;
            }
        }
        // Sparks
        for (int i = 0; i < 14; ++i) {
            float ang = randf() * 6.28318f;
            float spd = 60.0f + randf() * 140.0f;
            uint16_t col = (rand_int(3) == 0) ? Renderer::rgb(255, 255, 200)
                         : (rand_int(2) == 0) ? Renderer::rgb(255, 160, 40)
                         : Renderer::rgb(255, 80, 20);
            spawn_particle(x, y, cosf(ang)*spd, sinf(ang)*spd, 0.35f + randf()*0.35f, col, 1.5f + randf()*2.0f);
        }
        // Smoke
        for (int i = 0; i < 8; ++i) {
            float ang = randf() * 6.28318f;
            float spd = 15.0f + randf() * 40.0f;
            uint16_t col = Renderer::rgb(40 + rand_int(30), 40 + rand_int(30), 45 + rand_int(30));
            spawn_particle(x, y, cosf(ang)*spd, sinf(ang)*spd - 20.0f, 0.7f + randf()*0.5f, col, 3.0f + randf()*3.0f);
        }
    }

    void update_explosions(float dt) {
        for (auto& ex : explosions) {
            if (!ex.active) continue;
            ex.life -= dt;
            ex.flash -= dt;
            ex.radius += (ex.max_radius - ex.radius) * 10.0f * dt;
            if (ex.life <= 0.0f) ex.active = false;
        }
        for (auto& p : particles) {
            if (!p.active) continue;
            p.x += p.vx * dt;
            p.y += p.vy * dt;
            p.vx *= 0.92f;
            p.vy *= 0.92f;
            p.vy += 30.0f * dt; // slight gravity for smoke
            p.life -= dt;
            if (p.life <= 0.0f) p.active = false;
        }
    }

